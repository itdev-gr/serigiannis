// Περιεχόμενο του Οδηγού Χρήσης (/admin/odigos). Απλά ελληνικά για το προσωπικό
// του γραφείου. Τα placeholders {hold_minutes}, {sales_window_days},
// {default_cutoff_min}, {refund_policy} αντικαθίστανται στο render με τις
// ζωντανές τιμές των Ρυθμίσεων Κρατήσεων, ώστε ο οδηγός να μη «μένει πίσω».

export type OdigosBlock =
  | { kind: 'p'; text: string }
  | { kind: 'steps'; items: string[] }
  | { kind: 'tip'; text: string }
  | { kind: 'warning'; text: string }
  | { kind: 'table'; head: string[]; rows: string[][] }
  | { kind: 'link'; href: string; label: string };

export type OdigosSection = {
  id: string;
  group: string;
  title: string;
  keywords: string[];
  blocks: OdigosBlock[];
};

/** Αντικατάσταση placeholders σε όλο το περιεχόμενο (καθαρή συνάρτηση). */
export function withValues(sections: OdigosSection[], vars: Record<string, string>): OdigosSection[] {
  const sub = (s: string) => s.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m);
  return sections.map((sec) => ({
    ...sec,
    blocks: sec.blocks.map((b): OdigosBlock => {
      switch (b.kind) {
        case 'p':
        case 'tip':
        case 'warning':
          return { ...b, text: sub(b.text) };
        case 'steps':
          return { ...b, items: b.items.map(sub) };
        case 'table':
          return { ...b, head: b.head.map(sub), rows: b.rows.map((r) => r.map(sub)) };
        case 'link':
          return b;
      }
    }),
  }));
}

