-- 0032: σύντομη περιγραφή (short_description) ανά εκδρομή.
--
-- ΓΙΑΤΙ: η σελίδα /tour/<slug> έδειχνε το ίδιο κείμενο (tours.summary) δύο
-- φορές — ως εισαγωγική παράγραφο κάτω από τον τίτλο και ξανά στην ενότητα
-- «Περιγραφή» πιο κάτω. Το γραφείο θέλει ξεχωριστό, σύντομο κείμενο 1–2
-- προτάσεων για το πάνω μέρος, ενώ η πλήρης περιγραφή μένει μόνο στην
-- ενότητα «Περιγραφή». Οι υπάρχουσες εκδρομές παίρνουν NULL: το πάνω μέρος
-- απλώς δεν δείχνει εισαγωγική παράγραφο μέχρι το γραφείο να τη συμπληρώσει,
-- ενώ SEO και κάρτες καταλόγου κρατούν το summary ως εφεδρικό.
--
-- Καμία αλλαγή σε RLS (οι πολιτικές του 0002 είναι σε επίπεδο πίνακα και
-- καλύπτουν αυτόματα νέες στήλες) και σε RPC.
--
-- Εφαρμογή: ΧΕΙΡΟΚΙΝΗΤΑ στο project lucwtnzdvcpcdcmfxbqp (SQL editor), ΠΡΙΝ
-- το push — αλλιώς το admin σπάει στην αποθήκευση εκδρομής. Ξανατρέξιμο
-- ακίνδυνο (add column if not exists, idempotent update).

alter table public.tours
  add column if not exists short_description text;

-- Η δοκιμαστική εκδρομή του 0031 δείχνει και το νέο πεδίο συμπληρωμένο.
update public.tours
   set short_description = 'Μονοήμερη δοκιμαστική απόδραση με πούλμαν, ξενάγηση και ελεύθερο χρόνο — υπάρχει μόνο για να βλέπει το γραφείο μια γεμάτη σελίδα.'
 where slug = 'dokimastiki-ekdromi'
   and short_description is null;
